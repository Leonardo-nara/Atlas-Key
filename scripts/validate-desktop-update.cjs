const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const root = path.resolve(__dirname, "../apps/desktop");
const pkg = require(path.join(root, "package.json"));
const release = path.join(root, "release");
const name = `Mototake-Setup-${pkg.version}.exe`;
const exe = fs.readFileSync(path.join(release, name));
const manifest = fs.readFileSync(path.join(release, "latest.yml"), "utf8");
const feed = fs.readFileSync(path.join(release, "win-unpacked/resources/app-update.yml"), "utf8");
assert(manifest.includes(`version: ${pkg.version}`));
assert(manifest.includes(`url: ${name}`));
const sha512 = crypto.createHash("sha512").update(exe).digest("base64");
assert(manifest.includes(`sha512: ${sha512}`));
assert(manifest.includes(`size: ${exe.length}`));
assert(fs.statSync(path.join(release, `${name}.blockmap`)).size > 0);
for (const value of ["provider: github", "owner: Leonardo-nara", "repo: Atlas-Key", "tagNamePrefix: desktop-v"]) assert(feed.includes(value));
assert(!/token:|password:|secret:/i.test(feed));
const sha256 = crypto.createHash("sha256").update(exe).digest("hex");
fs.writeFileSync(path.join(release, `${name}.sha256.txt`), `${sha256}  ${name}\n`);
console.log(`PASS: NSIS, latest.yml SHA-512/size, blockmap, public feed. SHA-256: ${sha256}`);
